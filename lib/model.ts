// Token Radar, model radar-2: one sealed snapshot in, one ranked board out.
//
// The board covers every slug on the snapshot's watchlist (the floor, never the
// ceiling) and adds the pre-token protocols below the floor with the most TVL:
// the early rows the radar exists to find. A protocol is pre-token when its
// record carries no token (no market cap, no CoinGecko id, no symbol). Live-token
// protocols are kept apart and shown at the market's own value, never mixed into
// the ranked board.
//
// Implied value follows only from the snapshot's own figures, and no protocol
// name is ever special-cased:
//
//   catMult    = the category's median mcap / TVL among the snapshot's own
//                live-token protocols (at least 3 samples; the global median
//                when a category has fewer), clamped to [0.05, 1.50]
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365)
//   breadth    = 1 + 0.03 x min(chains - 1, 5)
//   implied    = max(1, round(tvl_usd x catMult x growthMult x maturity x breadth))
//
// The category multiple is learned from the same snapshot the board reads: a
// lending token trades at a different multiple of TVL than a DEX token does,
// and the market's own live protocols say what that multiple is. The dashboard
// prints the table so a reader can check it.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

